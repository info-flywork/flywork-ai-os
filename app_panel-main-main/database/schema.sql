CREATE DATABASE IF NOT EXISTS app_panel
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
USE app_panel;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('SUPER_ADMIN', 'ADMIN', 'USER') NOT NULL DEFAULT 'USER',
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS login_verification_challenges (
  id CHAR(36) PRIMARY KEY,
  user_id INT NOT NULL,
  code_hash VARCHAR(255) NOT NULL,
  expires_at DATETIME NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_login_challenge_user
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  INDEX idx_login_challenge_user (user_id),
  INDEX idx_login_challenge_expires (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS applications (
  id INT AUTO_INCREMENT PRIMARY KEY,
  app_name VARCHAR(120) NOT NULL,
  bundle_id VARCHAR(180) NOT NULL UNIQUE,
  icon_url VARCHAR(500) DEFAULT NULL,
  api_base_url VARCHAR(600) DEFAULT NULL,
  panel_slug VARCHAR(64) DEFAULT NULL,
  panel_api_key VARCHAR(255) DEFAULT NULL,
  revenuecat_project_id VARCHAR(64) DEFAULT NULL,
  analyse_api_url VARCHAR(600) DEFAULT NULL,
  health_api_url VARCHAR(600) DEFAULT NULL,
  users_api_url VARCHAR(600) DEFAULT NULL,
  latest_version VARCHAR(20) NOT NULL DEFAULT '1.0.0',
  status ENUM('READY', 'PREPARE', 'ISSUE') NOT NULL DEFAULT 'PREPARE',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
